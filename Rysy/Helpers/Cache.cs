namespace Rysy.Helpers;

public class Cache<T> where T : class? {
    public CacheToken Token { get; }
    public Func<T> Generator { get; }

    private ulong _lastVersion;

    private T? _cached;

    public Cache(CacheToken token, Func<T> generator) {
        Token = token;
        Generator = generator;
        _lastVersion = token.Version;
    }

    public T Value {
        get {
            if (_lastVersion != Token.Version) {
                _lastVersion = Token.Version;
                _cached = null;
            }

            return _cached ??= Generator();
        }
    }
    
    public bool HasCachedValue => _cached is not null && _lastVersion == Token.Version;

    /// <summary>
    /// Creates a new cache, whose value is generated by calling <paramref name="transform"/> on this cache's <see cref="Value"/>.
    /// This new cache will get invalided at the same time as this cache.
    /// </summary>
    public Cache<TNew> Chain<TNew>(Func<T, TNew> transform) where TNew : class? {
        var cache = new Cache<TNew>(Token, () => transform(Value));

        return cache;
    }

    public void Clear() => _cached = null;

    public static Cache<T> CreateUnchanging(T value) {
        return new Cache<T>(new CacheToken(), () => value);
    }
}
